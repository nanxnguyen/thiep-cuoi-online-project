// Generates privacy-safe seed rows for public.templates from the code catalog.
// Usage: node scripts/seed-templates.mjs            (prints INSERT statements)
// The output is appended to supabase/migrations/202610090001_admin.sql.
// Colors stay in code (lib/templates.ts) and are resolved client-side by id.
import { templateSamples, templates } from "../lib/templates.ts";

const STYLES = new Set(["Truyền thống", "Tối giản", "Hoa", "Cổ điển", "Lãng mạn", "Hiện đại"]);
const BADGES = new Set(["", "MỚI", "HOT"]);

const byId = new Map(templates.map((t) => [t.id, t.name]));
const sql = (v) => `'${String(v).replace(/'/g, "''")}'`;

const rows = Object.entries(templateSamples).map(([id, sample]) => {
  const name = byId.get(id);
  if (!name) throw new Error(`templateSamples key "${id}" has no entry in the templates catalog`);
  if (!STYLES.has(sample.style)) throw new Error(`template "${id}" has unknown style "${sample.style}"`);
  if (!BADGES.has(sample.badge)) throw new Error(`template "${id}" has unknown badge "${sample.badge}"`);
  if (!Number.isInteger(sample.pop) || sample.pop < 0 || sample.pop > 100) {
    throw new Error(`template "${id}" pop out of range: ${sample.pop}`);
  }
  return `insert into public.templates (id, name, style, badge, pop) values (${sql(id)}, ${sql(name)}, ${sql(sample.style)}, ${sql(sample.badge)}, ${sample.pop}) on conflict (id) do nothing;`;
});

console.log(`-- Seed generated by scripts/seed-templates.mjs (${rows.length} rows).`);
console.log(rows.join("\n"));
