alter table public.templates enable row level security;

-- The only anon policy: visible (non-hidden) templates. Admins go through
-- the service role, which bypasses RLS; authenticated has no policy (deny by
-- default). is_flagged needs no policy: only the service role touches it.
create policy templates_anon_visible on public.templates
for select to anon using (not hidden);

